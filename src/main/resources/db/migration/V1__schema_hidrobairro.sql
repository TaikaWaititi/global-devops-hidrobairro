CREATE TABLE usuario_hb (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(120 CHAR) NOT NULL,
    email VARCHAR2(180 CHAR) NOT NULL,
    senha_hash VARCHAR2(255 CHAR) NOT NULL,
    papel VARCHAR2(20 CHAR) NOT NULL,
    ativo CHAR(1) DEFAULT 'S' NOT NULL,
    criado_em TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_usuario_hb_email UNIQUE (email),
    CONSTRAINT ck_usuario_hb_papel CHECK (papel IN ('CIDADAO', 'GESTOR')),
    CONSTRAINT ck_usuario_hb_ativo CHECK (ativo IN ('S', 'N'))
);
CREATE TABLE ponto_monitoramento_hb (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(120 CHAR) NOT NULL,
    subprefeitura VARCHAR2(80 CHAR) NOT NULL,
    bairro VARCHAR2(80 CHAR) NOT NULL,
    zona VARCHAR2(20 CHAR) NOT NULL,
    latitude NUMBER(10,7),
    longitude NUMBER(10,7),
    limiar_alerta_cm NUMBER(8,2) NOT NULL,
    ativo CHAR(1) DEFAULT 'S' NOT NULL,
    criado_em TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_ponto_hb_ativo CHECK (ativo IN ('S', 'N')),
    CONSTRAINT ck_ponto_hb_limiar CHECK (limiar_alerta_cm > 0)
);
CREATE TABLE leitura_hb (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_id NUMBER(19) NOT NULL,
    nivel_cm NUMBER(8,2) NOT NULL,
    coletado_em TIMESTAMP(6) NOT NULL,
    origem VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT fk_leitura_hb_ponto FOREIGN KEY (ponto_id) REFERENCES ponto_monitoramento_hb(id)
);
CREATE TABLE alerta_hb (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_id NUMBER(19) NOT NULL,
    leitura_id NUMBER(19),
    nivel_cm NUMBER(8,2) NOT NULL,
    severidade VARCHAR2(255 CHAR) NOT NULL,
    mensagem VARCHAR2(400 CHAR) NOT NULL,
    status VARCHAR2(255 CHAR) NOT NULL,
    criado_em TIMESTAMP(6) NOT NULL,
    encerrado_em TIMESTAMP(6),
    CONSTRAINT fk_alerta_hb_ponto FOREIGN KEY (ponto_id) REFERENCES ponto_monitoramento_hb(id),
    CONSTRAINT fk_alerta_hb_leitura FOREIGN KEY (leitura_id) REFERENCES leitura_hb(id)
);
CREATE INDEX ix_leitura_hb_ponto ON leitura_hb(ponto_id);
CREATE INDEX ix_alerta_hb_ponto_status ON alerta_hb(ponto_id, status);
CREATE INDEX ix_alerta_hb_leitura ON alerta_hb(leitura_id);
